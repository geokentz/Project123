# ===== Program 1: Name Cases (2.4) =====
# Menyimpan nama lengkap, lalu mencetak nama dalam tiga format huruf.
name = "Chris Hemsworth"
print(name.lower()) # semua huruf kecil
print(name.upper()) # semua huruf besar
print(name.title()) # huruf pertama setiap kata besar

